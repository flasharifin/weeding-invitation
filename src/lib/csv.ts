// Penyusun CSV aman untuk Excel/Sheets: kutip semua sel, netralkan formula (CSV injection),
// dan awali BOM agar karakter UTF-8 terbaca benar.
const cell = (v: unknown) => {
  let s = v == null ? "" : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;
  return `"${s.replace(/"/g, '""')}"`;
};

export function toCsv(header: string[], rows: unknown[][]) {
  return "﻿" + [header, ...rows].map((r) => r.map(cell).join(",")).join("\r\n");
}
